import { beforeEach, expect, it, vi } from 'vitest';
import { POST } from '@/app/api/mobile/train/plans/commands/route';
import { authenticateNativeRequest } from '@/lib/auth/native-request';
import { log } from '@/lib/logger';
vi.mock('@/lib/auth/native-request', () => ({ authenticateNativeRequest: vi.fn() }));
vi.mock('@/lib/logger', () => ({ log: { error: vi.fn() } }));
const owner = '64220000-0000-4000-8000-000000000001', occurrence = '64220000-0000-4000-8000-000000000002', operation = '64220000-0000-4000-8000-000000000003', workout = '64220000-0000-4000-8000-000000000004';
const body = { protocolVersion: 1, ownerId: owner, operationId: operation, command: { kind: 'link-workout', workoutId: workout, occurrenceId: occurrence } };
const receipt = { operation: 'link-workout', operationId: operation, ownerId: owner, workoutId: workout, occurrenceId: occurrence, linkedAt: '2026-10-26T10:00:00.123456+00:00', acceptedAt: '2026-10-26T10:00:00.123456+00:00' };
const rpc = vi.fn();
const request = (value: unknown = body) => new Request('https://example.test/api/mobile/train/plans/commands', { method: 'POST', headers: { authorization: 'Bearer captured' }, body: JSON.stringify(value) });
beforeEach(() => { rpc.mockReset().mockResolvedValue({ data: { status: 'accepted', receipt }, error: null }); vi.mocked(log.error).mockClear(); vi.mocked(authenticateNativeRequest).mockResolvedValue({ userId: owner, client: { rpc } } as never); });
it('acknowledges the exact separate association receipt and keeps retry identity unchanged', async () => {
    const response = await POST(request());
    expect(response.status).toBe(200);
    expect(await response.json()).toEqual({ protocolVersion: 1, receipt });
    expect(await (await POST(request())).json()).toEqual({ protocolVersion: 1, receipt });
    expect(rpc).toHaveBeenLastCalledWith('execute_train_plan_command', { p_request: body });
});
it('does not acknowledge another owner or an uncertain RPC response', async () => {
    expect((await POST(request({ ...body, ownerId: occurrence }))).status).toBe(403);
    expect(rpc).not.toHaveBeenCalled();
    rpc.mockResolvedValue({ data: null, error: { message: 'private database detail' } });
    expect((await POST(request())).status).toBe(503);
    expect(log.error).toHaveBeenCalledWith('[train] Plan request unavailable', undefined, { classification: 'rpc_error' });
    rpc.mockResolvedValue({ data: { status: 'accepted', receipt: { ...receipt, workoutId: occurrence } }, error: null });
    expect((await POST(request())).status).toBe(503);
});
it('retains missing/changed as durable rejection while keeping unexpected failures unacknowledged', async () => {
    const rejection = { operation: 'link-workout', operationId: operation, ownerId: owner, workoutId: workout, occurrenceId: occurrence, rejectedAt: '2026-10-26T10:00:00Z', code: 'not_found' };
    rpc.mockResolvedValue({ data: { status: 'not_found', rejection }, error: null });
    const result = await POST(request());
    expect(result.status).toBe(404);
    expect(await result.json()).toEqual({ protocolVersion: 1, error: { code: 'not_found' }, rejection });
    rpc.mockResolvedValue({ data: { status: 'changed', rejection }, error: null });
    expect((await POST(request())).status).toBe(503);
    vi.mocked(authenticateNativeRequest).mockRejectedValue(new Error('private token'));
    expect((await POST(request())).status).toBe(503);
    expect(log.error).toHaveBeenCalledWith('[train] Plan request unavailable', undefined, { classification: 'unexpected_exception' });
});
import { POST as readDay } from '@/app/api/mobile/train/day/route';
import fixture from '@/tests/fixtures/workout-templates.json';
it('returns exact full captures for the persisted day and preserves the raw scanned cursor', async () => {
    const completion = structuredClone(fixture.completionEnvelope.completion);
    completion.ownerId = owner;
    completion.templateOrigin.content.ownerId = owner;
    const row = { id: completion.id, user_id: owner, status: 'completed', title: 'Workout', started_at: completion.startedAt, completed_at: completion.completedAt, duration_seconds: completion.durationSeconds, routine_id: completion.templateOrigin.content.id, native_completion: null, recorded_completion: completion };
    const cursor = { startedAt: '2026-10-25T11:00:00.123456+00:00', id: operation };
    rpc.mockResolvedValue({ data: { protocolVersion: 1, ownerId: owner, day: '2026-10-25', workouts: [{ record: row, link: null }, { record: { ...row, id: operation, recorded_completion: { version: 99, workoutDay: '2026-10-25' } }, link: null }], nextCursor: cursor }, error: null });
    const response = await readDay(request({ protocolVersion: 1, ownerId: owner, day: '2026-10-25', before: null }));
    expect(response.status).toBe(200);
    expect(await response.json()).toEqual({ protocolVersion: 1, ownerId: owner, day: '2026-10-25', workouts: [{ workout: completion, link: null }], nextCursor: cursor });
    expect(rpc).toHaveBeenCalledWith('read_train_workout_day', { p_day: '2026-10-25', p_before: null });
});
import { GET as listPlans } from '@/app/api/mobile/train/plans/route';
import { GET as readPlan } from '@/app/api/mobile/train/plans/[id]/route';
import { GET as readLink } from '@/app/api/mobile/train/plans/workouts/[id]/route';
const version = { taskVersion: operation, occurrenceVersion: occurrence, seriesToken: 1, eventVersion: workout };
const plan = { ownerId: owner, occurrenceId: occurrence, seriesId: operation, taskId: workout, scheduledDate: '2026-10-25', plannedDay: '2026-10-29', title: 'Moved training', timezone: 'UTC', state: 'open', completed: false, templateId: null, version };
it('reads a moved occurrence independently of its original date and fails closed on foreign/date-mismatched rows', async () => {
    rpc.mockResolvedValue({ data: { protocolVersion: 1, plan }, error: null });
    expect(await (await readPlan(new Request('https://example.test'), { params: Promise.resolve({ id: occurrence }) })).json()).toEqual({ protocolVersion: 1, plan });
    expect(rpc).toHaveBeenLastCalledWith('read_train_plans', { p_date: null, p_occurrence_id: occurrence, p_after: null });
    rpc.mockResolvedValue({ data: { protocolVersion: 1, ownerId: owner, plans: [plan], nextCursor: null }, error: null });
    expect((await listPlans(new Request('https://example.test/api/mobile/train/plans?date=2026-10-29'))).status).toBe(200);
    expect((await listPlans(new Request('https://example.test/api/mobile/train/plans?date=2026-10-25'))).status).toBe(503);
    rpc.mockResolvedValue({ data: { protocolVersion: 1, plan: { ...plan, ownerId: workout } }, error: null });
    expect((await readPlan(new Request('https://example.test'), { params: Promise.resolve({ id: occurrence }) })).status).toBe(503);
});
it('keeps absent links distinct from unavailable reads and authenticates every read', async () => {
    rpc.mockResolvedValue({ data: { protocolVersion: 1, link: null }, error: null });
    expect(await (await readLink(new Request('https://example.test'), { params: Promise.resolve({ id: workout }) })).json()).toEqual({ protocolVersion: 1, link: null });
    expect(rpc).toHaveBeenLastCalledWith('read_train_workout_link', { p_workout_id: workout });
    rpc.mockResolvedValue({ data: { status: 'not_found' }, error: null });
    expect((await readPlan(new Request('https://example.test'), { params: Promise.resolve({ id: occurrence }) })).status).toBe(404);
    rpc.mockResolvedValue({ data: null, error: { message: 'private' } });
    expect((await readLink(new Request('https://example.test'), { params: Promise.resolve({ id: workout }) })).status).toBe(503);
    expect((await listPlans(new Request('https://example.test/api/mobile/train/plans?date=2026-10-29'))).status).toBe(503);
    vi.mocked(authenticateNativeRequest).mockResolvedValue(null);
    expect((await readDay(request())).status).toBe(401);
    expect((await listPlans(new Request('https://example.test'))).status).toBe(401);
    expect((await POST(request())).status).toBe(401);
});
it('returns an exact changed-plan rejection for explicit reconfirmation and no success for a failed day refresh', async () => {
    const input = { protocolVersion: 1, ownerId: owner, operationId: operation, command: { kind: 'fulfill-plan', occurrenceId: occurrence, expected: version } };
    const rejection = { operation: 'fulfill-plan', ownerId: owner, operationId: operation, occurrenceId: occurrence, rejectedAt: '2026-10-29T10:00:00Z', code: 'changed', current: plan };
    rpc.mockResolvedValue({ data: { status: 'changed', rejection }, error: null });
    const response = await POST(request(input));
    expect(response.status).toBe(409);
    expect(await response.json()).toEqual({ protocolVersion: 1, error: { code: 'changed' }, rejection });
    rpc.mockResolvedValue({ data: null, error: { message: 'private' } });
    expect((await readDay(request({ protocolVersion: 1, ownerId: owner, day: '2026-10-29', before: null }))).status).toBe(503);
    expect((await readDay(request({ protocolVersion: 1, ownerId: workout, day: '2026-10-29', before: null }))).status).toBe(403);
    expect((await readDay(request({ protocolVersion: 1, ownerId: owner, day: '2026-02-30', before: null }))).status).toBe(400);
});
